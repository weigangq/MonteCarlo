"""#Mutual Information - Raw and Standardized

$MI_n(X_n;Y_n) = H(X_n) + H(Y_n) - H(X_n,Y_n) $ Raw MI


$MIR_n =\frac{MI_n}{min(H(X_n), H(Y_n)}$ Standardized MI
"""

def MIR(sampx, sampy):
  MI = ent_vec(sampx) + ent_vec(sampy) - joint_ent(sampx, sampy)


  m = min(ent_vec(sampx), ent_vec(sampy))

  MIR = MI/m

  return MIR

