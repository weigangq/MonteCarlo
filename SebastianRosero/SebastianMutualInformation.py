def JointFreq(sampx, sampy):
  pairs = list(zip(sampx, sampy))
  freq = {}
  freq [(1, 0)] = pairs.count((1, 0)) / len(pairs)
  freq [(0, 0)] = pairs.count((0, 0)) / len(pairs)
  freq [(0, 1)] = pairs.count((0, 1)) / len(pairs)
  freq [(1, 1)] = pairs.count((1, 1)) / len(pairs)


  return freq

def joint_ent (samp_x, samp_y):


  j_freq = JointFreq(samp_x, samp_y)

  j_entropy = 0.0
  for key in j_freq.keys():
    if j_freq[key] > 0:
      j_entropy -= j_freq[key] * math.log2(j_freq[key])




  return j_entropy

