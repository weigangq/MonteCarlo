"""#Measuring Linkage with D and D'
$D= P(AB) - P(A) P(B)$    A=1 a=0 , B=1, a = 1


$D' = \frac{D}{min(P(A) * P(b), P(a) * P(B)))} if D>0 $

$D' = \frac{D}{max(-P(A) * P(B), -P(a) * P(b)} if D<0 $

$r^2 = \frac{D}{P(A) P(a) P(B) P(b)}$

Like entropy, D is measure of independence of Alleles between sites.
"""

def D_prime(samp1, samp2):

  freq_xy = JointFreq(samp1, samp2)
  freq_x = freq(samp1)
  freq_y = freq(samp2)

  D = freq_xy[(1,1)] - freq_x[(1)] * freq_y[(1)]

  if D > 0:
    D_p = D / min(freq_x[(1)] * freq_y[(0)], freq_x[(0)] * freq_y[(1)])
  else:
    D_p = D / max(-freq_x[(1)] * freq_y[(1)], -freq_x[(0)] * freq_y[(0)])

  return D_p

