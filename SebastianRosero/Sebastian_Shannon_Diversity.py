"""#Joint Entropy

$$H(X,Y)= -\sum_{(x,y) \in (X,Y)} p(x,y)log_2(p(x,y)) $$
"""

def joint_ent (prob):
  samp_x = random.choices([0,1], weights = [prob, 1-prob], k=10)

  samp_y = random.choices([0,1], weights = [prob, 1-prob], k=10)

  data = pd.DataFrame({'X': samp_x, 'Y' : samp_y})

  p_dist = pd.crosstab(data['X'], data['Y'], normalize = 'all')
  p_dist = p_dist.values.tolist()
  j_entropy = 0.0
  for row in p_dist:
    for p in row:
      if p > 0:
        j_entropy -= p * math.log2(p)




  return j_entropy

