"""#Shannon Diversity
Shannon Diversity, or entropy measure uncertainty

$$H(X) = \sum_{x \in X} p(x_i)log_2(p(x_i))$$
"""

def entropy(probs):
  # Auto-correct by adding the missing probability if total < 1
  total = sum(probs)

  if total < 1.0:
    missing = 1.0 - total
    probs.append(missing)
  elif total > 1.0:
    raise ValueError("Probabilities sum to more than 1")

 # Calculates Entropy
  value=0
  for p in probs:
    if p != 0:
      value += p * math.log2(p)

  return -value

