import numpy as np
from scipy.stats import norm, binom

#input:  sample_size and r the correlation coefficient
#output: two binary vectors of size sample_size with correlation approx r.
def createBinaryList(sample_size,r):
  z = np.random.randn(2, sample_size)
  #print(z)
  if 0<r and r<1:
    my_list = [1,r,r,1]
    sigma = np.array(my_list).reshape(2,2)
    s = np.linalg.cholesky(sigma)    #for symmetric matrices cholesky does a outputs a lower triangular matrix. s=Lower.Upper o
    z = np.dot(s,z)
  #print(z)

  u = norm.cdf(z)  # translates the CDF elementwise, returning a matrix of probabilities.  F(z_ij)=P(Z<=z_ij)
  row_probs = u[0, :]
  quantiles = binom.ppf(row_probs,n=1,p=0.5)
  site1 = quantiles
  site2 = site1
  if r < 1:
    row_probs = u[1, :]
    quantiles = binom.ppf(row_probs,n=1,p=0.5)
    site2 = quantiles
  return [r,site1,site2]

