def sumLog(int):
  if int == 0:
    return 0
  return (int * math.log2(int))

def JointEntropy(samp_pop1, samp_pop2):
    x = combineTwoLists(samp_pop1, samp_pop2)
    p1 = x.count((0,0))/len(samp_pop1)
    p2 = x.count((0,1))/len(samp_pop1)
    p3 = x.count((1,0))/len(samp_pop1)
    p4 = x.count((1,1))/len(samp_pop1)
    return -((sumLog(p1)) + sumLog(p2) + sumLog(p3) + sumLog(p4))

