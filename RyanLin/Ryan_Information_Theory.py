"""#Mutual Information
MI(X,Y) = H(X) + H(Y) - H(X,Y)
**input**: Two binary lists of the same length representing allele at two loci
**output**: MI(List1, List2)

H(X) = ent, H(Y) = ent, H(X,Y) = Joint ent
"""

def MutualInformationStandard(samp_pop1, samp_pop2):
  ent1 = entropy(freq(samp_pop1))
  ent2 = entropy(freq(samp_pop2))
  J_ent = JointEntropy(samp_pop1, samp_pop2)
  Mut_Inf = ent1 + ent2 - J_ent
  MIR = Mut_Inf/min(ent1,ent2)
  return MIR

