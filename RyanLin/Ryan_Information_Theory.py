"""#Detecting Linkage with $D' \text{and } r^2 $
$D = P(AB) - P(A)*P(B)

$D' = \frac{D}{min(P(A)*P(b),(a)*P(B)}$ $ \text { if } D>0 $

$D' = \frac{D}{max(-P(A)*P(B),-P(a)*P(b))}$ $\text { if } D<0 $
"""

def Dprime(samp_pop1, samp_pop2):
  freq_x1 = samp_pop1.count(1)/len(samp_pop1)
  freq_x0 = samp_pop1.count(0)/len(samp_pop1)
  freq_y1 = samp_pop2.count(1)/len(samp_pop2)
  freq_y0 = samp_pop2.count(0)/len(samp_pop2)
  combList = combineTwoLists(samp_pop1, samp_pop2)
  freq_xy11 = combList.count((1,1))/len(combList)
  D = ((freq_xy11) - (freq_x1)*(freq_y1))
  if D > 0:
    Dp = D/(min((freq_x1)*(freq_y0), (freq_x0)*(freq_y1)))
  if D < 0:
    Dp = D/(max(-(freq_x1)*(freq_y1), -(freq_x0)*(freq_y0)))
  return Dp

