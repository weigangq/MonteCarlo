"""#Entropy
$H(X) = -\sum_{x\in X}p(x_i)log_2 (p(x_i))$
"""

def entropy(prob):
  p1 = prob
  p2 = 1 - prob
  if p1 == 0 or p2 == 0:
    return 0
  ent = -((p1 * math.log2(p1)) + (p2 * math.log2(p2)))
  return ent

