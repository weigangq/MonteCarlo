def DnaTranslation(dna, frame):
  dna = SwapTU(dna) #replaces lowercase letters with uppercase letters and then swaps all T's with U's
  AmAcid = ""
  if frame < 0:
    x = abs(frame)
    dna = ReverseComplement(dna) # if frame is negative you need to reverse the strand before you begin reading the frame
    AmAcid = Translation(dna, x)
    return AmAcid
  elif frame > 0:
    AmAcid = Translation(dna, frame)
    return AmAcid

