"""SwapTU Function, the initial function necessary for reading dna strands as amino acids."""

def SwapTU(dna):
  dna = dna.upper()
  dna = re.sub("T", "U", dna)
  return dna

"""Reversing DNA function for negative frames"""

def ReverseComplement(dna):
  reversedString = ""
  dna.upper()
  for i in range(len(dna)):
    reversedString += dna[len(dna)-i-1]
  newString = ""
  for i in range(len(dna)):
    if reversedString[i] == "A":
      newString += "U"
    if reversedString[i] == "U":
      newString += "A"
    if reversedString[i] == "G":
      newString += "C"
    if reversedString[i] == "C":
      newString += "G"
  return newString

def Translation(dna, start):
   AmAcid = ""
   for x in range(start-1, len(dna)-2, 3):
      element = dna[x:(x + 3)]
      first_index = gc[gc[0] == element].index[0]
      AmAcid += gc.iloc[first_index,1]
   return AmAcid

